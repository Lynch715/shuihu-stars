changed = renamed = dropped = 0
log = []

for b in rows:
    n = b['name']
    if n in FIX_MEMBERS:
        names, why = FIX_MEMBERS[n]
        new = ids(*names)
        if new != b['members']:
            old = '、'.join(H[m]['name'] for m in b['members'] if m in H)
            b['members'] = new
            changed += 1
            log.append(('成员', n, old + ' → ' + '、'.join(names), why))
    if n in RENAME and RENAME[n][0]:
        newname, why = RENAME[n]
        b['name'] = newname
        b['desc'] = f"{newname}：{b['effect']}"
        renamed += 1
        log.append(('名字', n, '→ ' + newname, why))

keep = []
for b in rows:
    # 用改名前的原名判断是否并掉
    if b.get('_orig', b['name']) in DROP or b['name'] in DROP:
        dropped += 1
        log.append(('并掉', b['name'], '', DROP.get(b['name'], '')))
        continue
    keep.append(b)

for kind, name, what, why in log:
    print(f'[{kind}] {name}　{what}')
    if why: print(f'        {why}')

if isinstance(B, dict):
    D['bonds'] = {b['id']: b for b in keep}
else:
    D['bonds'] = keep

# ── 自检 ─────────────────────────────────────────────────
